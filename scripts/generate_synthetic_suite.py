#!/usr/bin/env python3
"""
Generate (or verify) the IMUCA v2 synthetic benchmark suite.

Usage:
    python scripts/generate_synthetic_suite.py            # generate; unchanged files are left untouched
    python scripts/generate_synthetic_suite.py --verify   # regenerate in memory and compare SHA-256 with manifest
    python scripts/generate_synthetic_suite.py --force    # allow overwriting raw files whose content differs

Outputs:
    data/synthetic/{voltage,current,temperature,fault_detection}/<scenario_id>.csv
    data/synthetic/malformed/MAL_*.csv
    data/synthetic/metadata/<scenario_id>.metadata.json, suite_manifest.json,
                            fault_events.csv, malformed_manifest.json
    docs/DATASET_CATALOG.md

The Milestone-1 datasets directly under data/synthetic/ are not touched.
"""

import argparse
import json
import sys
from pathlib import Path

WORKSPACE_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(WORKSPACE_ROOT))

if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

from src.imuca.synthetic_suite import SyntheticSuiteGenerator, GENERATOR_VERSION, FAULT_OBSERVABILITY, write_text_if_changed

CONFIG_PATH = WORKSPACE_ROOT / "config" / "synthetic_suite_config.json"
OUTPUT_ROOT = WORKSPACE_ROOT / "data" / "synthetic"
CATALOG_PATH = WORKSPACE_ROOT / "docs" / "DATASET_CATALOG.md"


def write_catalog(manifest: dict, gen: SyntheticSuiteGenerator, output_root: Path = OUTPUT_ROOT, catalog_path: Path = CATALOG_PATH) -> str:
    rel_root = output_root.relative_to(WORKSPACE_ROOT).as_posix()
    title = "Suite v2" if manifest["suite_id"] == "IMUCA_SYNTH_SUITE_V2" else f"`{manifest['suite_id']}`"
    lines = [
        f"# IMUCA — Synthetic Dataset Catalog ({title})",
        "",
        f"> Auto-generated by `scripts/generate_synthetic_suite.py` from `{rel_root}/metadata/suite_manifest.json`. Do not edit by hand.",
        ">",
        f"> {manifest['disclaimer']}",
        "",
        f"- **Suite:** `{manifest['suite_id']}`  ",
        f"- **Generator:** {manifest['generator']} v{GENERATOR_VERSION} (`src/imuca/synthetic_suite.py`)  ",
        f"- **Configuration:** `{manifest['config_file']}` (SHA-256 `{manifest['config_sha256'][:16]}…`)  ",
        f"- **Seed roots:** calibration `{manifest['seed_roots']['calibration']}`, validation `{manifest['seed_roots']['validation']}`, test `{manifest['seed_roots']['test']}`; reference realisation seed `{manifest['reference_realization_seed']}`  ",
        f"- **Scenarios:** {manifest['scenario_count']}  ",
        f"- **Total records:** {manifest['total_records']:,}",
        "",
        "Every CSV contains all runs of one scenario; the `partition` column assigns each run (`experiment_id`) to exactly one of calibration / validation / test. Per-scenario metadata, including the full column dictionary, error models and the fault-event table, is in `data/synthetic/metadata/<scenario_id>.metadata.json`.",
        "",
        "Legacy Milestone-1 datasets (`data/synthetic/nominal_voltage_baseline.csv`, `current_calibration_sweep.csv`, `temperature_drift_scenario.csv`, `fault_stress_scenario.csv`) are produced by the frozen v1.0.0 generator and are not part of this suite.",
        "",
    ]
    groups = {}
    for f in manifest["files"]:
        groups.setdefault(f["group"], []).append(f)
    titles = {"voltage": "DC voltage", "current": "DC current", "temperature": "Temperature", "fault_detection": "Fault-detection benchmark"}
    for grp in ["voltage", "current", "temperature", "fault_detection"]:
        if grp not in groups:
            continue
        lines += [f"## {titles[grp]} (`{rel_root}/{grp}/`)", "",
                  "| File | Device | Records (cal / val / test) | Runs | Fault rows | Events | Missing rate | Description |",
                  "|---|---|---|---|---|---|---|---|"]
        for f in groups[grp]:
            pr = f["partition_records"]
            lines.append(
                f"| `{Path(f['csv_file']).name}` | {f['device_id']} | {f['record_count']:,} ({pr['calibration']:,} / {pr['validation']:,} / {pr['test']:,}) "
                f"| {f['run_count']} | {100 * f['fault_row_fraction']:.1f} % | {f['fault_events']} | {100 * f['missing_rate']:.2f} % | {f['description']} |"
            )
        lines.append("")

    lines += ["## Run seeds", "", "| Scenario | Run seeds (experiment_id: seed) |", "|---|---|"]
    for f in manifest["files"]:
        seeds = ", ".join(f"{k.split('-')[-1]}={v}" for k, v in f["run_seeds"].items())
        lines.append(f"| `{f['scenario_id']}` | {seeds} |")
    lines.append("")

    lines += ["## Fault classes and observability", "",
              "| Fault class | Observability from the DUT signal |", "|---|---|"]
    for k, v in FAULT_OBSERVABILITY.items():
        lines.append(f"| `{k}` | {v} |")
    lines.append("")

    with open(output_root / "metadata" / "malformed_manifest.json", "r", encoding="utf-8") as fh:
        mal = json.load(fh)
    lines += [f"## Malformed ingestion fixtures (`{rel_root}/malformed/`)", "",
              "| File | Description | Expected outcome |", "|---|---|---|"]
    for name, m in mal.items():
        exp = ", ".join(f"{k}={v}" for k, v in m.items() if k != "description")
        lines.append(f"| `{name}` | {m['description']} | {exp} |")
    lines.append("")

    lines += ["## SHA-256 checksums", "", "| File | SHA-256 |", "|---|---|"]
    for f in manifest["files"]:
        lines.append(f"| `{f['csv_file']}` | `{f['csv_sha256']}` |")
    lines.append("")
    return write_text_if_changed(str(catalog_path), "\n".join(lines))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--verify", action="store_true", help="verify on-disk files against a fresh regeneration")
    ap.add_argument("--force", action="store_true", help="overwrite raw files whose content differs")
    ap.add_argument("--config", default=str(CONFIG_PATH), help="suite configuration (default: v2 suite)")
    ap.add_argument("--output-root", default=str(OUTPUT_ROOT), help="dataset root directory (default: data/synthetic)")
    ap.add_argument("--catalog", default=str(CATALOG_PATH), help="catalog Markdown path (default: docs/DATASET_CATALOG.md)")
    args = ap.parse_args()
    output_root = Path(args.output_root).resolve()

    gen = SyntheticSuiteGenerator.from_file(str(Path(args.config).resolve()))
    if args.verify:
        mismatches = gen.verify_against_manifest(str(output_root))
        if mismatches:
            print("VERIFY FAILED:", ", ".join(mismatches))
            return 1
        print(f"VERIFY OK: {len(gen.scenarios)} scenarios regenerate bit-identically.")
        return 0

    manifest = gen.export(str(output_root), overwrite=args.force)
    catalog_status = write_catalog(manifest, gen, output_root, Path(args.catalog).resolve())
    counts = {}
    for s in manifest["file_status"].values():
        counts[s] = counts.get(s, 0) + 1
    print(f"Suite {manifest['suite_id']} v{GENERATOR_VERSION}: {manifest['scenario_count']} scenarios, "
          f"{manifest['total_records']:,} records. File status: {counts}")
    print(f"Auxiliary files: {manifest['auxiliary_file_status']}; catalog: {catalog_status}")
    print(f"Manifest: {output_root / 'metadata' / 'suite_manifest.json'}")
    print(f"Catalog:  {Path(args.catalog).resolve()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
